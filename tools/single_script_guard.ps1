# 単一 .ps1 版の本体（日本語のまま）を、BOM が落ちても動く形に包む。tools\new_single_script.ps1 が読み込んで使う。
# 設計は docs/design/structure/single-script.md の「文字コード」。
#
# 困りごと: Windows PowerShell 5.1 は、BOM の無い UTF-8 のファイルを ANSI コードページ（日本語の Windows では CP932）で読む。
#   CP932 は 2 バイトで 1 文字のため、日本語の文字の最後のバイトが、次の ASCII の文字（バッククォート・{・}・英字・引用符）を
#   飲み込み、構文が壊れる。5.1 は実行の前にファイル全体を構文として読むため、頭のコードも動かない。
#
# 直し方: 日本語を含む本体全体を、単一引用符のヒアストリング（データ）に入れる。ヒアストリングの中は、どう読み違えても
#   構文にならない（改行・' ・#・@ は飲み込まれない）。頭（param と判定・展開のコード）は ASCII だけで書き、BOM があってもなくても
#   同じ手順（本体の文字列を ScriptBlock にして dot-source）で動かす。BOM が落ちて読み違えたときは、頭が自分のファイルを
#   UTF-8 で読み直して本体を取り出す。
#
# 受け入れる副作用:
#   - ScriptBlock の中では $PSScriptRoot・$PSCommandPath が空になるため、本体の中の使い方は ${tebunkoRoot}・${tebunkoPath}
#     （頭が決める）に AST で書き換える。
#   - エラーの表示にファイル名が出ない（行番号は、頭の分の空行を足して、ファイルの行番号に合わせる）。
#   - LanguageMode が FullLanguage でなければ、頭が英語 1 行を出して終了コード 1 で止まる。
#
# 範囲の外: Shift_JIS で保存し直した単一 .ps1（5.1 では日本語以外の文字が ? になり、7 では ASCII の案内を出して止まる）。

$script:guardProbeChar = [string][char]0x30A2
$script:guardBodyStart = '${tebunkoBody} = @'''
$script:guardRewriteNames = @{
    'psscriptroot' = '${tebunkoRoot}'
    'pscommandpath' = '${tebunkoPath}'
}

# 文字列を構文木に読む。構文エラーがあれば止める
function readGuardAst {
    param (
        [string]$text,
        [string]$label
    )

    $tokens = $null
    $errors = $null
    $ast = [System.Management.Automation.Language.Parser]::ParseInput($text, [ref]$tokens, [ref]$errors)
    if ($errors.Count -gt 0) {
        throw "$label の構文エラー: $($errors[0].Message)（$($errors[0].Extent.StartLineNumber) 行目）"
    }
    return $ast
}

# $PSScriptRoot・$PSCommandPath の変数（文字列の中のものも含む）を、頭が決める名前に書き換える
function rewriteScriptPathVariables {
    param ([string]$text)

    $ast = readGuardAst $text "書き換え前の本体"
    $names = $script:guardRewriteNames
    $targets = @($ast.FindAll({
                param ($node)
                $node -is [System.Management.Automation.Language.VariableExpressionAst] -and
                $names.ContainsKey($node.VariablePath.UserPath.ToLowerInvariant())
            }, $true) | Sort-Object { $_.Extent.StartOffset } -Descending)

    $builder = New-Object System.Text.StringBuilder($text)
    foreach ($node in $targets) {
        $start = $node.Extent.StartOffset
        $length = $node.Extent.EndOffset - $start
        [void]$builder.Remove($start, $length).Insert($start, $names[$node.VariablePath.UserPath.ToLowerInvariant()])
    }
    $result = $builder.ToString()

    $remain = @((readGuardAst $result "書き換え後の本体").FindAll({
                param ($node)
                $node -is [System.Management.Automation.Language.VariableExpressionAst] -and
                $names.ContainsKey($node.VariablePath.UserPath.ToLowerInvariant())
            }, $true))
    if ($remain.Count -gt 0) {
        throw "`$PSScriptRoot・`$PSCommandPath の書き換えが残っています（$($remain.Count) か所）。"
    }
    return $result
}

# 本体（日本語を含んでよい）を、頭（ASCII）＋ヒアストリングの本体＋尾（ASCII）に包む
function convertToGuardedScript {
    param ([string]$text)

    $ast = readGuardAst $text "本体"
    if (!$ast.ParamBlock) {
        throw "本体に param ブロックがありません（頭の param を本体と同じにするため要る）。"
    }
    $paramText = $ast.ParamBlock.Extent.Text
    if ($paramText -match '[^\x00-\x7F]') {
        throw "本体の param ブロックに ASCII 以外の文字があります（頭は ASCII だけで書くため）。"
    }

    $body = rewriteScriptPathVariables $text
    if ($body -match "(?m)^@@'@") {
        throw "本体に、行の先頭が @@'@ の行があります（ヒアストリングの中の '@ の行の退避に使うため）。"
    }
    # 行の先頭が '@ の行（本体の中のヒアストリングの終わり）は、外側のヒアストリングを閉じてしまうので退避する
    $payload = [regex]::Replace($body, "(?m)^'@", "@@'@").TrimEnd("`r", "`n")

    $head = New-Object System.Collections.Generic.List[string]
    foreach ($line in @(
            '# tebunko single-file script (generated by tools\new_single_script.ps1). Do not edit by hand.',
            '# The Japanese body below is kept as DATA in a here-string, so reading this file with a',
            '# wrong code page (for example after the BOM was dropped) cannot break the parsing.',
            '# Design: docs/design/structure/single-script.md')) {
        [void]$head.Add($line)
    }
    foreach ($line in ($paramText -split "\r?\n")) {
        [void]$head.Add($line)
    }
    foreach ($line in @(
            'if ($ExecutionContext.SessionState.LanguageMode -ne ''FullLanguage'') {',
            '    Write-Host ''tebunko: this script needs PowerShell FullLanguage mode and cannot run here.''',
            '    exit 1',
            '}',
            '${tebunkoRoot} = $PSScriptRoot',
            '${tebunkoPath} = $PSCommandPath',
            '${tebunkoProbe} = @''',
            $script:guardProbeChar,
            '''@',
            $script:guardBodyStart)) {
        [void]$head.Add($line)
    }
    # 本体の 1 行目がファイルの何行目になるか（頭の行数）。空行をこの数だけ足して、エラーの行番号をファイルに合わせる
    $padLines = $head.Count

    $tail = @(
        '''@',
        '${tebunkoSource} = ${tebunkoBody}',
        'if (${tebunkoProbe}.Trim() -ne [string][char]0x30A2) {',
        '    # Read with a wrong code page: read this file again as UTF-8 and take the body out of it.',
        '    if (!${tebunkoPath}) {',
        '        throw ''tebunko: cannot read this script as UTF-8 (no file path). Run it from a file saved as UTF-8.''',
        '    }',
        '    ${tebunkoRaw} = [System.IO.File]::ReadAllText(${tebunkoPath}, (New-Object System.Text.UTF8Encoding($false)))',
        '    ${tebunkoMatch} = [regex]::Match(${tebunkoRaw}, ''(?s)\$\{tebunkoBody\} = @''''\r?\n(.*?)\r?\n''''@'')',
        '    if (!${tebunkoMatch}.Success -or !${tebunkoRaw}.Contains([string][char]0x30A2)) {',
        '        throw ''tebunko: cannot read this script as UTF-8. Save it as UTF-8 (with BOM) and run it again.''',
        '    }',
        '    ${tebunkoSource} = ${tebunkoMatch}.Groups[1].Value',
        '}',
        '${tebunkoSource} = [regex]::Replace(${tebunkoSource}, ''(?m)^@@''''@'', ''''''@'')',
        ('${tebunkoSource} = ("`r`n" * ' + $padLines + ') + ${tebunkoSource}'),
        '. ([scriptblock]::Create(${tebunkoSource})) @PSBoundParameters')

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.AddRange($head)
    [void]$lines.Add($payload)
    $lines.AddRange([string[]]$tail)
    return ($lines -join "`r`n") + "`r`n"
}

# 包んだ結果を確かめる。1 つでも外れれば止める
#   1) 構文エラー 0
#   2) UTF-8 のバイトを CP932 で読み違えても、構文エラー 0（BOM が落ちた 5.1 の読み方）
#   3) 頭と尾は ASCII だけ（頭の中の判定用の 1 文字だけが例外）
#   4) 行の先頭が '@ の行は、頭の判定・本体の 2 本の終わりだけ
function assertGuardedScript {
    param (
        [string]$text,
        [string]$label
    )

    [void](readGuardAst $text "$label（UTF-8 で読む）")

    $encoding = $null
    try {
        $encoding = [System.Text.Encoding]::GetEncoding(932)
    }
    catch {
        [System.Text.Encoding]::RegisterProvider([System.Text.CodePagesEncodingProvider]::Instance)
        $encoding = [System.Text.Encoding]::GetEncoding(932)
    }
    $bytes = (New-Object System.Text.UTF8Encoding($false)).GetBytes($text)
    [void](readGuardAst ($encoding.GetString($bytes)) "$label（CP932 で読み違えた場合）")

    $bodyStart = $text.IndexOf($script:guardBodyStart + "`r`n")
    $bodyEnd = $text.LastIndexOf("`r`n'@`r`n")
    if ($bodyStart -lt 0 -or $bodyEnd -lt $bodyStart) {
        throw "$label に、本体の始まり・終わりの印がありません。"
    }
    $headText = $text.Substring(0, $bodyStart).Replace($script:guardProbeChar, "")
    $tailText = $text.Substring($bodyEnd)
    if ($headText -match '[^\x00-\x7F]') {
        throw "$label の頭に、ASCII 以外の文字があります。"
    }
    if ($tailText -match '[^\x00-\x7F]') {
        throw "$label の尾に、ASCII 以外の文字があります。"
    }
    if ($text.IndexOf($script:guardProbeChar) -lt 0) {
        throw "$label に、判定用の文字がありません。"
    }
    $closers = @([regex]::Matches($text, "(?m)^'@\r?$")).Count
    if ($closers -ne 2) {
        throw "$label の、行の先頭が '@ の行が 2 本ではありません（$closers 本）。"
    }
}
